#!/bin/bash
# -*- mode: shell-script -*-
# mod_tarantool build.sh — pre-make helper for FreeSWITCH 1.10 / 1.11+
#
# Problem:
#   FreeSWITCH's modmake.rules links a module from $(MODNAME).lo plus
#   $(LOCAL_OBJS); by default only mod_tarantool.c is compiled, so every
#   tnt_* helper (tnt_client.c, tnt_rules.c, ...) is MISSING from the .so,
#   yielding "undefined symbol: tnt_result_free" at dlopen time.
#
# Fix:
#   Generate a module Makefile that (a) defines LOCAL_OBJS BEFORE including
#   modmake.rules (GNU make expands prerequisites at parse time, so the
#   variable must already be visible when the mod_tarantool.la rule is read)
#   and (b) provides EXPLICIT .lo build rules for each helper C file
#   (the implicit .c.lo suffix rule is bypassed by FreeSWITCH's recursive
#   make invocation). Then `make mod_tarantool` compiles and links all.
#
# Usage (from the FreeSWITCH source root, as a pre-make step):
#   ./src/mod/databases/mod_tarantool/build.sh
#   make mod_tarantool
#   make mod_tarantool-install
#
# (module may live in any subdirectory; root is auto-detected by looking
#  for build/modmake.rules, e.g. src/mod/omnipbx/mod_tarantool works too)
set -e

# ---- locate FreeSWITCH root by walking up from this script ----
SELF="$(cd "$(dirname "$0")" && pwd)"
FS_ROOT=""
d="$SELF"
while [ -n "$d" ]; do
	if [ -f "$d/build/modmake.rules" ]; then
		FS_ROOT="$d"
		break
	fi
	n="$(dirname "$d")"
	[ "$n" = "$d" ] && break
	d="$n"
done

if [ -z "$FS_ROOT" ]; then
	echo "build.sh: ERROR: FreeSWITCH root not found" >&2
	echo "build.sh: (looked for build/modmake.rules above $SELF)" >&2
	exit 1
fi

MOD_REL="${SELF#$FS_ROOT/}"
echo "build.sh: FreeSWITCH root : $FS_ROOT"
echo "build.sh: module dir      : $MOD_REL"

# ---- sanity: Makefile.am must carry the full source list ----
if ! grep -q 'tnt_client\.c' "$SELF/Makefile.am"; then
	echo "build.sh: ERROR: $SELF/Makefile.am lacks tnt_client.c" >&2
	echo "build.sh: (the pre-make source list is incomplete)" >&2
	exit 1
fi

# ---- extra C files to build and link into the module ----
EXTRA_SOURCES="
	tnt_client.c
	tnt_rules.c
	tnt_sql.c
	tnt_stats.c
	tnt_tcache.c
	circuit_breaker.c
	mp_decode.c
"
LOCAL_OBJS=""
BUILD_RULES=""
for s in $EXTRA_SOURCES; do
	[ -f "$SELF/$s" ] || { echo "build.sh: ERROR: missing source $s" >&2; exit 1; }
	lo="${s%.c}.lo"
	LOCAL_OBJS="$LOCAL_OBJS $lo"
	BUILD_RULES="$BUILD_RULES
$lo: $s
	@echo \"Compiling \$<...\"
	@\$(LTCOMPILE) -c -o \$@ \$<
"
done
LOCAL_OBJS="$(echo $LOCAL_OBJS)"     # collapse spaces

# ---- relative BASE from module dir up to the FreeSWITCH root ----
BASE="$(realpath --relative-to="$SELF" "$FS_ROOT")"
[ -n "$BASE" ] || BASE="."

# ---- generate the module Makefile ----
# IMPORTANT: LOCAL_OBJS must appear BEFORE `include modmake.rules` because
# GNU make expands rule prerequisites at parse time.
cat > "$SELF/Makefile" <<EOF
# --- mod_tarantool extra sources (generated by build.sh, safe to re-run) ---
LOCAL_OBJS =$LOCAL_OBJS

# GNU gcc >= 8 reports -Wformat-truncation even for snprintf() calls that
# are already length-guarded; FreeSWITCH's -Werror turns it into a build
# failure. Downgrade it to a warning for this module.
LOCAL_CFLAGS = -Wno-error=format-truncation

BASE=$BASE
include \$(BASE)/build/modmake.rules

# Explicit build rules for the helper objects (the implicit .c.lo suffix
# rule is bypassed by FreeSWITCH's recursive make invocation).
$BUILD_RULES
EOF

echo "build.sh: generated $MOD_REL/Makefile"
echo "build.sh: LOCAL_OBJS =$LOCAL_OBJS"
echo "build.sh: done. Continue with:"
echo "  make mod_tarantool"
echo "  make mod_tarantool-install"